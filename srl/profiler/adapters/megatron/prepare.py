"""Candidate manifests, launch specs, and torchrun commands."""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

from ...schema import ProfileValidationError
from ...search_space import TrainingCandidate
from .config import (
    RECOMPUTE_METHOD,
    RECOMPUTE_NUM_LAYERS,
    MegatronBridgeConfig,
)

# The torchrun child entry point. Referenced by module path rather than imported
# so that nothing on the CLI import path pulls in torch or megatron.
LAUNCH_MODULE = "srl.profiler.adapters.megatron.launch"

LAUNCH_SPEC_VERSION = 1


def write_candidate_manifest(
    path: str | Path,
    candidates: list[TrainingCandidate],
) -> Path:
    """Write constrained candidates in a stable JSON document."""
    destination = Path(path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "schema_version": 1,
        "candidates": [candidate.to_dict() for candidate in candidates],
    }
    destination.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    return destination


def read_candidate_manifest(path: str | Path) -> list[TrainingCandidate]:
    """Read candidates generated by SimRL."""
    with Path(path).open(encoding="utf-8") as handle:
        value = json.load(handle)
    if value.get("schema_version") != 1:
        raise ProfileValidationError("Unsupported candidate manifest schema.")
    return [TrainingCandidate.from_dict(item) for item in value["candidates"]]


def effective_sequence_shape(candidate: TrainingCandidate) -> tuple[int, ...]:
    """Return the shape the launcher actually trains on.

    BSHD pads every sequence to the longest, giving ``(max_len,) * mbs``. THD
    concatenates them, giving the single total ``(sum(sequence_shape),)``.
    """
    if candidate.packing == "thd":
        return (sum(candidate.sequence_shape),)
    padded_length = max(candidate.sequence_shape)
    return (padded_length,) * candidate.micro_batch_size


def build_launch_spec(
    config: MegatronBridgeConfig,
    candidate: TrainingCandidate,
    run_dir: Path,
) -> dict[str, Any]:
    """
    Describe one candidate for the torchrun child.

    Every setting the child needs travels in this document. The child applies it
    to a `ConfigContainer` in Python, so no configuration is marshalled through
    a CLI that could silently drop it.
    """
    vocab_size = config.model.extra.get("vocab_size")
    if vocab_size is None:
        raise ProfileValidationError(
            "The HuggingFace config must provide vocab_size so NullTokenizer keeps "
            "the embedding and LM head shapes faithful to the real model."
        )
    parallelism = candidate.parallelism
    packing = candidate.packing
    seq_length = (
        sum(candidate.sequence_shape) if packing == "thd" else max(candidate.sequence_shape)
    )
    return {
        "schema_version": LAUNCH_SPEC_VERSION,
        "run_dir": str(run_dir),
        "recipe": {
            "family": config.model_family_name,
            "name": config.model_recipe_name,
            "task": config.model_task,
        },
        "model_path": config.model.name,
        "parallelism": {
            "tp": parallelism.tp,
            "pp": parallelism.pp,
            "cp": parallelism.cp,
            # The launcher applies this to `expert_model_parallel_size`. Omitting it would
            # leave a MoE recipe's own tuned value in place against an overridden TP/PP.
            "ep": parallelism.ep,
            "world_size": parallelism.world_size,
        },
        "micro_batch_size": candidate.micro_batch_size,
        "global_batch_size": candidate.global_batch_size,
        "num_microbatches": candidate.num_microbatches,
        "seq_length": seq_length,
        "packing": packing,
        # Recorded, not acted on: a provider whose forward derives rotary positions from
        # `input_ids` cannot be pipelined by this profiler. Megatron's `get_batch` returns
        # all-None for a middle pipeline stage *before* consulting the data iterator
        # (`gpt_step.py`, `if (not is_first) and (not is_last): return None, ...`), which is
        # correct for a dense GPT where a middle stage receives hidden states. The
        # Qwen3.5-VL MoE forward instead calls `get_rope_index(input_ids, ...)` whenever
        # `position_ids is None`, so every PP>1 candidate dies with
        # `AttributeError: 'NoneType' object has no attribute 'shape'`. No batch-reader
        # patch can fix that, because the iterator is never reached. The sweep uses PP=1 for
        # such a model. This field is here so the artifact records why.
        "derives_position_ids_from_input_ids": "VL" in str(config.model.architecture or "")
        or "Conditional" in str(config.model.architecture or ""),
        # The launcher builds `cu_seqlens` from these and the sidecar records them,
        # so the measured buffer and the fitted shape cannot drift apart.
        "sequence_lengths": list(candidate.sequence_shape),
        "recompute": candidate.recompute,
        "recompute_method": RECOMPUTE_METHOD,
        "recompute_num_layers": RECOMPUTE_NUM_LAYERS,
        "mtp_num_layers": config.mtp_num_layers,
        "train_iters": config.max_steps,
        "warmup_steps": config.warmup_steps,
        "vocab_size": int(vocab_size),
        "num_layers_override": config.num_layers_override,
        "compute_dtype": config.compute_dtype,
        "parameter_dtype": config.parameter_dtype,
        "gradient_dtype": config.gradient_dtype,
        "optimizer_state_dtype": config.optimizer_state_dtype,
        "distributed_optimizer": config.distributed_optimizer,
        "resolved_config": str(run_dir / "ConfigContainer.yaml"),
    }


def build_launch_command(
    candidate: TrainingCandidate,
    spec_path: Path,
    *,
    nnodes: int = 1,
    node_rank: int = 0,
    master_addr: str | None = None,
    master_port: int | None = None,
) -> list[str]:
    """
    Build the torchrun command for one candidate.

    A single node uses `--standalone`. Multiple nodes pass an explicit rendezvous
    so the same child module serves both without a second code path.
    """
    if nnodes <= 0:
        raise ProfileValidationError("nnodes must be positive.")
    if not 0 <= node_rank < nnodes:
        raise ProfileValidationError(f"node_rank {node_rank} is outside [0, {nnodes}).")
    world_size = candidate.parallelism.world_size
    if world_size % nnodes != 0:
        raise ProfileValidationError(
            f"world_size {world_size} is not divisible across {nnodes} nodes."
        )
    command = ["torchrun"]
    if nnodes == 1:
        command.append("--standalone")
    else:
        if master_addr is None or master_port is None:
            raise ProfileValidationError(
                "Multi-node launches require master_addr and master_port."
            )
        command.extend(
            (
                "--node-rank",
                str(node_rank),
                "--master-addr",
                master_addr,
                "--master-port",
                str(master_port),
            )
        )
    command.extend(
        (
            "--nnodes",
            str(nnodes),
            "--nproc-per-node",
            str(world_size // nnodes),
            "-m",
            LAUNCH_MODULE,
            "--spec",
            str(spec_path),
        )
    )
    return command


def prepare_bridge_candidate(
    config: MegatronBridgeConfig,
    candidate: TrainingCandidate,
    *,
    nnodes: int = 1,
    node_rank: int = 0,
    master_addr: str | None = None,
    master_port: int | None = None,
) -> tuple[list[str], Path]:
    """Write one candidate's launch spec and immutable manifest."""
    run_dir = config.raw_root / candidate.candidate_id
    run_dir.mkdir(parents=True, exist_ok=True)
    spec = build_launch_spec(config, candidate, run_dir)
    spec_path = run_dir / "launch_spec.json"
    spec_path.write_text(json.dumps(spec, indent=2), encoding="utf-8")
    command = build_launch_command(
        candidate,
        spec_path,
        nnodes=nnodes,
        node_rank=node_rank,
        master_addr=master_addr,
        master_port=master_port,
    )
    manifest = {
        "adapter": "megatron_bridge",
        "backend": "local",
        "launcher": {"nnodes": nnodes, "node_rank": node_rank, "python": sys.executable},
        "candidate": candidate.to_dict(),
        "requested_sequence_shape": list(candidate.sequence_shape),
        "effective_sequence_shape": list(effective_sequence_shape(candidate)),
        "recompute_method": RECOMPUTE_METHOD,
        "recompute_num_layers": RECOMPUTE_NUM_LAYERS,
        "mtp_num_layers": config.mtp_num_layers,
        # Recorded so the collected record's architecture matches what actually ran.
        # The memory model derives its activation footprint from the layer count, so a
        # descriptor left at the checkpoint's depth would misprice an overridden run.
        "num_layers_override": config.num_layers_override,
        "command": command,
        "launch_spec": str(spec_path),
        "resolved_config": spec["resolved_config"],
        "backend_version": config.backend_version,
        "source_commit": config.source_commit,
    }
    (run_dir / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    return command, run_dir
