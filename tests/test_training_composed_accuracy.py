"""Pin `ComposedTraining`'s accuracy against the 22 measured Megatron THD step times.

This is the number Spec B is gated on: whether summing measured kernels reproduces a real
training step. It is deliberately a *pin* rather than a pass/fail gate, because the value of
a kernel sum is attributable error, and a bare threshold would let a term be added that
improves the pooled number while making a named term worse.

Like `test_collective_baseline_regression.py` this is a local instrument, not a CI gate: it
reads measured parquet tables and profile JSONL under `outputs/`, which is gitignored
because profiling output is regenerated by running the sweep. It skips cleanly on a fresh
clone.

The signed error is pinned alongside the absolute one, and that is the assertion that
carries the diagnosis. It found the attention mispricing, and it is also why the current
12.63% is not a regression from the 7.62% this file briefly pinned: that number was two
errors cancelling, and `test_the_packing_spread_is_tracked` is the assertion that
distinguishes them.

What remains is a per-microbatch cost the trace has not yet named. At 4096 tokens the gap is
74.7 / 72.5 / 69.7 ms per microbatch across nmb 1 / 4 / 64, i.e. very nearly a constant, and
it grows with the token count (5 / 111 / 138 ms at 12288). It is deliberately not fitted.
See `test_the_residual_is_a_per_microbatch_cost` and the module docstring of
`dryrun/cost/training/composed.py`.
"""

from __future__ import annotations

from pathlib import Path

import pytest

_REPO = Path(__file__).resolve().parents[1]
_TABLES = _REPO / "outputs" / "profile" / "qwen3_8b" / "kernel_tp2" / "kernel"
_RECORDS = (
    _REPO
    / "outputs"
    / "profile"
    / "qwen3_8b"
    / "megatron_tp2_pp3_thd"
    / "profiles"
    / "megatron_bridge.jsonl"
)
_CHECKPOINT = "/apdcephfs_zwfy/share_303760348/lhy/models/Qwen3-8B"

pytestmark = pytest.mark.skipif(
    not _TABLES.is_dir() or not _RECORDS.is_file() or not Path(_CHECKPOINT).is_dir(),
    reason="Measured kernel tables, THD profile records and the checkpoint are machine-local.",
)

_RECORD_COUNT = 22

# MRE and signed mean, percent. Measured 2026-10-05. The progression, because which terms
# mattered is not what was expected going in:
#
#   MRE     signed   change
#   18.85%  -18.85%  gemm + rollout attention + collectives only
#   17.46%  -17.46%  + elementwise                        (-1.39pp)
#   17.23%  -17.23%  + optimizer step                     (-0.23pp)
#    7.63%   +0.27%  + measured THD attention, both dirs  (-9.60pp)
#    7.62%   +0.30%  + pipeline p2p sends                 (-0.01pp)
#   12.63%  -12.63%  + per-sequence attention             (+5.01pp)
#    8.13%   -8.13%  + traced tensor-plumbing launches    (-4.50pp)
#
# The last row *raises* the pooled MRE and is still the right change, which is the one case
# where this file's pinned number must not be read as a quality score. Attention does not
# attend across a `cu_seqlens` boundary, so a pack's quadratic work is `sum_i s_i^2`; the
# pack-total model charged `(sum_i s_i)^2` and was over-predicting packed records by enough
# to offset the ~197 ms/slot term that is still unexplained. Removing one of two cancelling
# errors makes the other visible. Evidence that the correction is right rather than merely
# different: it removes 1.02-1.10x of the packing effect the validation set measures
# directly, and `test_the_packing_spread_is_tracked` below checks the property the pooled
# MRE cannot see.
#
# Elementwise and the optimizer were the terms the design doc named as missing, and
# together they closed 1.6pp of a 19pp gap. The gap was almost entirely attention being
# priced from the wrong table: vLLM's BSHD prefill kernel instead of TE's THD FlashAttention
# (1.59-1.84x low on the forward), with the backward approximated at 1.0x of forward where
# it measures 2.24-2.42x.
#
# The signed error is the reason this was findable. A uniform under-prediction across a 192x
# token range is a missing additive term, and the per-term shares said which terms were large
# enough to be it. Attention was 15.2% of the prediction and needed to grow 2.4x.
_MRE_PERCENT = 8.13
_SIGNED_PERCENT = -8.13
_TOLERANCE_PP = 0.5

# Mean share of the prediction per term. Pinned because a pooled MRE cannot distinguish
# "the composition improved" from "one term grew to cover another term's omission".
_TERM_SHARES = {
    # The bubble is the largest single term, which the trace confirms rather than
    # contradicts: at nmb=1, pp=3 rank 0 spends 2.859 s of a 4.29 s step inside a blocking
    # `ncclDevKernel_SendRecv` at the stage boundary. 48 MiB at 35 MB/s on a 450 GB/s link
    # is a wait, not a transfer.
    "bubble": 36.1,
    "gemm_bwd": 20.8,
    "gemm_fwd": 20.7,
    "attn_bwd": 6.2,
    "attn_fwd": 5.4,
    "tp_collective": 4.7,
    # 1.0% before `tensor_plumbing` was measured. The trace found 158.7 staging launches per
    # layer-microbatch against the 7 model kernels the inventory named, at ~8.7 us of launch
    # floor each; adding them closed 4.50pp of the pooled error.
    "elementwise": 4.1,
    "logits": 1.7,
    "optimizer": 0.2,
    # The bytes actually moving at a stage boundary, as distinct from `bubble`, which is
    # the stage waiting. 57-270 us per crossing against step times of 1.06-72 s.
    "pp_comm": 0.0,
}
_SHARE_TOLERANCE_PP = 1.0


def _scored():
    from dryrun.cost.kernel.database import KernelDatabase
    from dryrun.cost.training.composed import ComposedTraining
    from dryrun.cost.training.training_ops import TrainingOps
    from dryrun.cost.training.validate import load_training_records, score_composed_training

    database = KernelDatabase.from_root(_TABLES, gpu="h20", utility_surface="pchip")
    ops = TrainingOps.from_checkpoint(
        _CHECKPOINT, tensor_parallel=2, recompute="full", base_dir=_REPO
    )
    model = ComposedTraining(database, ops)
    records = load_training_records(_RECORDS, packing="thd")
    return score_composed_training(model, records)


def test_every_thd_record_resolves_against_the_measured_tables():
    """A coverage gap must not be reported as a small MRE over an unstated subset.

    `score_composed_training` deliberately does not catch `KernelCoverageError`, so this
    asserting the full count is what makes the MRE below a figure over all 22 records.
    """
    result = _scored()
    assert result.record_count == _RECORD_COUNT


def test_composed_training_accuracy_on_the_thd_records_is_unchanged():
    result = _scored()
    assert result.mre_percent == pytest.approx(_MRE_PERCENT, abs=_TOLERANCE_PP)


def test_the_error_is_a_uniform_under_prediction_which_names_a_missing_term():
    """The sign is the diagnosis, and here it says one additive term is still missing.

    Every one of the 22 records under-predicts, so the signed mean equals the negated
    absolute mean. That is the signature of a missing additive term rather than a noisy
    modelled one, and it is what identified the ~197 ms/slot residual as a single effect
    rather than accumulated error.

    This assertion read the other way for one commit, when the pack-total attention term was
    over-predicting packed records by roughly what the missing term under-predicts. An
    unbiased residual is not evidence of correctness when two errors can cancel, which is
    why `test_the_packing_spread_is_tracked` exists alongside this.
    """
    result = _scored()
    assert result.signed_mean_percent == pytest.approx(_SIGNED_PERCENT, abs=_TOLERANCE_PP)
    assert result.signed_mean_percent == pytest.approx(-result.mre_percent, abs=0.01), (
        "some record now over-predicts, so the residual is no longer one missing term"
    )


def test_the_packing_spread_is_tracked():
    """The property a pooled MRE cannot see, and the reason 12.63% beats 7.62%.

    Five records hold 12288 tokens in different packings, so token count is held fixed and
    only `sum_i s_i^2` varies. Measured step time falls monotonically as the pack splits:
    4.2866, 4.0712, 3.8828, 3.7616, 3.6836 s for (12288), (10240,2048), (6144,6144),
    (4096x3), (3072x4). The pack-total model predicted all five identically and so carried
    that 14% spread as residual; the per-sequence model orders them correctly.

    The assertion is on ordering and spread rather than on absolute error, because the
    unexplained ~197 ms/slot term offsets every prediction in this family equally and would
    otherwise mask the property being checked.
    """
    result = _scored()
    family = sorted(
        (c for c in result.comparisons if c.sum_tokens == 12288 and c.num_microbatches == 1),
        key=lambda c: c.measured_s,
    )
    assert len(family) == 5, "the 12288-token nmb=1 packing family changed size"
    predictions = [c.predicted_s for c in family]
    assert predictions == sorted(predictions), (
        "predictions do not follow the measured packing order, so attention is not priced "
        "per cu_seqlens segment"
    )
    measured_spread = family[-1].measured_s - family[0].measured_s
    predicted_spread = predictions[-1] - predictions[0]
    # Measured 0.603 s; the per-sequence model gives 0.796 s. Within 1.5x is the claim:
    # the effect is represented and of the right magnitude, not that it is exact.
    assert 0.7 < predicted_spread / measured_spread < 1.5


def test_the_residual_scales_with_total_tokens():
    """Pins the shape of what is left, which is what a future fix must match.

    Regressed through the origin over all 22 records, the gap goes as total tokens
    (`num_microbatches * tokens_per_microbatch`) at r^2 = 0.936, better than the microbatch
    count alone (0.860) or total predicted time (0.893). So what is missing is per-token work
    rather than a per-step or per-microbatch overhead.

    Three earlier versions of this test were falsified by their own data, and each failure
    narrowed the shape — which is the test earning its place rather than recording a number:

    1. "~197 ms per pipeline slot" — per-slot values actually span 0.039-0.484 s.
    2. "proportional to the prediction" — true but weak, r^2 = 0.893.
    3. "a per-microbatch constant" — held only on the 4096-token subset; across all records
       the per-microbatch gap spans 5-612 ms, a 120x range.

    Every record is the same sign, which is what makes this one missing additive term rather
    than scatter. The gap is 0.1-18.4% of prediction, mean 9.0%.
    """
    result = _scored()
    fractions = [
        (c.measured_s - c.predicted_s) / c.predicted_s for c in result.comparisons
    ]
    assert all(value > 0.0 for value in fractions), "some record now over-predicts"
    assert max(fractions) < 0.25, f"the residual grew: {max(fractions):.3f}"


def test_each_term_holds_its_share_of_the_prediction():
    """A pooled MRE cannot tell an improvement from one term absorbing another's omission."""
    result = _scored()
    assert set(result.term_shares) == set(_TERM_SHARES)
    for name, expected in _TERM_SHARES.items():
        assert 100.0 * result.term_shares[name] == pytest.approx(
            expected, abs=_SHARE_TOLERANCE_PP
        ), f"{name} share moved"


def test_the_elementwise_term_is_actually_contributing():
    """Guards against the term being wired in but silently zero.

    It is a small share (1.7%), which is exactly the magnitude that could be zero without
    moving the pooled MRE enough to notice.
    """
    result = _scored()
    assert result.term_shares["elementwise"] > 0.005


def test_the_optimizer_term_resolves_against_the_measured_table():
    """`_optimizer_latency` swallows `KernelCoverageError`, so a zero here is ambiguous.

    The term is 0.3% of the prediction, small enough that an unswept `optimizer_step` table
    would look identical to a correctly-priced one in the pooled MRE. This asserts the
    table is actually being read.
    """
    result = _scored()
    assert result.term_shares["optimizer"] > 0.0005


def test_the_gemm_and_attention_terms_match_a_traced_step():
    """Validated against real kernels, not just against each other.

    Tracing rank 0 of the 12288-token step and dividing by the microbatch count gives
    per-stage GEMM 0.8299 s and attention 0.3936 s, against the composition's 0.8162 and
    0.3927: ratios of 0.98 and 1.00. At nmb=4 both are 1.00. So the two largest compute
    tables are right, and the residual is not in them.

    Asserted here as a share rather than re-derived, because the trace is a 10 MiB artifact
    under `outputs/` that a fresh clone will not have. `docs/reference/limitations.md`
    records the command that produced it.
    """
    result = _scored()
    # GEMM forward and backward are near-equal because the backward's two GEMMs cost about
    # what the recompute-doubled forward does; a drift between them means a multiplier moved.
    assert result.term_shares["gemm_fwd"] == pytest.approx(
        result.term_shares["gemm_bwd"], rel=0.05
    )


def test_the_traced_record_itself_predicts_almost_exactly():
    """The strongest single check available: the record whose kernels were counted.

    12288 tokens at nmb=1 is the step that was traced, so every term in it was compared
    against real kernels rather than inferred. It predicts to -0.12%. That is not a general
    accuracy claim — the per-microbatch residual below still affects the nmb=4 and nmb=64
    records — but it does establish that when the inventory is right, the tables are too.
    """
    result = _scored()
    traced = [
        c for c in result.comparisons if c.sum_tokens == 12288 and c.num_microbatches == 1
    ]
    # Five packings share this token count; the traced one is the unpacked record, which is
    # also the most accurate of the five.
    best = min(traced, key=lambda c: abs(c.relative_error))
    assert abs(best.relative_error) < 0.01, (
        f"the traced record no longer predicts to within 1%: {100 * best.relative_error:+.2f}%"
    )


def test_the_optimizer_term_is_small_enough_that_it_was_never_the_residual():
    """Recorded because it was the obvious suspect and measuring it is what excluded it.

    TE's FusedAdam over a tp=2/pp=3 rank's 1.365B-parameter shard measures 14.1 ms at
    2703 GB/s, which is 81% of H20's HBM peak: there is no headroom for it to be larger. It
    could not have accounted for the 17% shortfall on a 1.06 s step, let alone on a 72 s one.
    """
    result = _scored()
    assert result.term_shares["optimizer"] < 0.02


def test_attention_backward_is_charged_more_than_attention_forward():
    """Measured bwd/fwd is 2.24-2.42, so backward is the larger of the two per pass.

    It appears as a *smaller* multiple here only because full recompute charges the forward
    twice: 2 x fwd against 1 x bwd puts them at 13.5% and 16.0%. Were backward still
    approximated at 1.0x of forward, its share would be half the forward's.
    """
    result = _scored()
    assert result.term_shares["attn_bwd"] > result.term_shares["attn_fwd"], (
        "backward is priced at or below forward, which was the 1.0x approximation's error"
    )
