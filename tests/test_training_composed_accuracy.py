"""Pin `ComposedTraining`'s accuracy against the 22 measured Megatron THD step times.

This is the number Spec B is gated on: whether summing measured kernels reproduces a real
training step. It is deliberately a *pin* rather than a pass/fail gate, because the value of
a kernel sum is attributable error, and a bare threshold would let a term be added that
improves the pooled number while making a named term worse.

Like `test_collective_baseline_regression.py` this is a local instrument, not a CI gate: it
reads measured parquet tables and profile JSONL under `outputs/`, which is gitignored
because profiling output is regenerated by running the sweep. It skips cleanly on a fresh
clone.

The signed error is pinned alongside the absolute one, and that is the assertion that
carries the diagnosis. Every one of the 22 records currently under-predicts, so the absolute
and signed figures are equal. If a future change makes them diverge, a term has started
over-predicting for some shapes and the composition's error is no longer one missing
additive term.
"""

from __future__ import annotations

from pathlib import Path

import pytest

_REPO = Path(__file__).resolve().parents[1]
_TABLES = _REPO / "outputs" / "profile" / "qwen3_8b" / "kernel_tp2" / "kernel"
_RECORDS = (
    _REPO
    / "outputs"
    / "profile"
    / "qwen3_8b"
    / "megatron_tp2_pp3_thd"
    / "profiles"
    / "megatron_bridge.jsonl"
)
_CHECKPOINT = "/apdcephfs_zwfy/share_303760348/lhy/models/Qwen3-8B"

pytestmark = pytest.mark.skipif(
    not _TABLES.is_dir() or not _RECORDS.is_file() or not Path(_CHECKPOINT).is_dir(),
    reason="Measured kernel tables, THD profile records and the checkpoint are machine-local.",
)

_RECORD_COUNT = 22

# MRE and signed mean, percent. Measured 2026-10-05 with the elementwise and optimizer
# terms wired in. The progression is the point:
#
#   18.85%  neither term
#   17.46%  + elementwise  (-1.39pp)
#   17.23%  + optimizer    (-0.23pp)
#
# The elementwise table was already swept and already held the four kinds Megatron runs; it
# was simply never queried, because `cost/kernel/database.py` had no `query_elementwise`.
# The optimizer term is newly measured (`ops/optimizer.py`), and its 0.23pp is consistent
# with the 14.1 ms direct measurement of TE's FusedAdam over a 1.365B shard.
_MRE_PERCENT = 17.23
_SIGNED_PERCENT = -17.23
_TOLERANCE_PP = 0.5

# Mean share of the prediction per term. Pinned because a pooled MRE cannot distinguish
# "the composition improved" from "one term grew to cover another term's omission".
_TERM_SHARES = {
    "gemm_bwd": 36.5,
    "gemm_fwd": 36.3,
    "attn_fwd": 10.1,
    "tp_collective": 8.2,
    "attn_bwd": 5.1,
    "logits": 1.9,
    "elementwise": 1.7,
    "optimizer": 0.3,
}
_SHARE_TOLERANCE_PP = 1.0


def _scored():
    from dryrun.cost.kernel.database import KernelDatabase
    from dryrun.cost.training.composed import ComposedTraining
    from dryrun.cost.training.training_ops import TrainingOps
    from dryrun.cost.training.validate import load_training_records, score_composed_training

    database = KernelDatabase.from_root(_TABLES, gpu="h20", utility_surface="pchip")
    ops = TrainingOps.from_checkpoint(
        _CHECKPOINT, tensor_parallel=2, recompute="full", base_dir=_REPO
    )
    model = ComposedTraining(database, ops)
    records = load_training_records(_RECORDS, packing="thd")
    return score_composed_training(model, records)


def test_every_thd_record_resolves_against_the_measured_tables():
    """A coverage gap must not be reported as a small MRE over an unstated subset.

    `score_composed_training` deliberately does not catch `KernelCoverageError`, so this
    asserting the full count is what makes the MRE below a figure over all 22 records.
    """
    result = _scored()
    assert result.record_count == _RECORD_COUNT


def test_composed_training_accuracy_on_the_thd_records_is_unchanged():
    result = _scored()
    assert result.mre_percent == pytest.approx(_MRE_PERCENT, abs=_TOLERANCE_PP)


def test_the_error_is_still_uniformly_an_under_prediction():
    """The sign is the diagnosis: a uniformly negative error means a missing additive term.

    Were it scattered around zero, a modelled term would be noisy; were it positive, the
    composition would be double-counting or ignoring overlap. Asserting that the signed mean
    equals the absolute mean is asserting that no record over-predicts.
    """
    result = _scored()
    assert result.signed_mean_percent == pytest.approx(_SIGNED_PERCENT, abs=_TOLERANCE_PP)
    assert result.signed_mean_percent == pytest.approx(-result.mre_percent, abs=0.01), (
        "some record now over-predicts; the residual is no longer one missing term"
    )


def test_the_residual_scales_with_work_rather_than_being_a_fixed_per_step_cost():
    """This is what rules out the optimizer step as the main gap, and it is load-bearing.

    An unmodelled fixed cost would be a constant number of seconds: large as a fraction of a
    1.06 s step and negligible against a 72 s one. The measured gap is 10-39% of the
    prediction across a 192x token range, so whatever is missing scales with the work. The
    assertion is that the gap/prediction ratio at the largest record is not an order of
    magnitude below the smallest, which is what a constant would give.
    """
    result = _scored()
    by_tokens = sorted(result.comparisons, key=lambda c: c.sum_tokens)
    smallest, largest = by_tokens[0], by_tokens[-1]
    assert largest.sum_tokens / smallest.sum_tokens > 100, "need a wide token range to test this"

    def shortfall(comparison) -> float:
        return (comparison.measured_s - comparison.predicted_s) / comparison.predicted_s

    assert shortfall(smallest) > 0.05
    assert shortfall(largest) > 0.5 * shortfall(smallest), (
        "the shortfall collapsed at scale, which would mean it is a fixed per-step cost"
    )


def test_each_term_holds_its_share_of_the_prediction():
    """A pooled MRE cannot tell an improvement from one term absorbing another's omission."""
    result = _scored()
    assert set(result.term_shares) == set(_TERM_SHARES)
    for name, expected in _TERM_SHARES.items():
        assert 100.0 * result.term_shares[name] == pytest.approx(
            expected, abs=_SHARE_TOLERANCE_PP
        ), f"{name} share moved"


def test_the_elementwise_term_is_actually_contributing():
    """Guards against the term being wired in but silently zero.

    It is a small share (1.7%), which is exactly the magnitude that could be zero without
    moving the pooled MRE enough to notice.
    """
    result = _scored()
    assert result.term_shares["elementwise"] > 0.005


def test_the_optimizer_term_resolves_against_the_measured_table():
    """`_optimizer_latency` swallows `KernelCoverageError`, so a zero here is ambiguous.

    The term is 0.3% of the prediction, small enough that an unswept `optimizer_step` table
    would look identical to a correctly-priced one in the pooled MRE. This asserts the
    table is actually being read.
    """
    result = _scored()
    assert result.term_shares["optimizer"] > 0.0005


def test_the_optimizer_term_is_too_small_to_be_the_residual():
    """The reason step 2 of the plan did not close the gap, asserted rather than narrated.

    TE's FusedAdam over a tp=2/pp=3 rank's 1.365B-parameter shard measures 14.1 ms at
    2703 GB/s, which is 81% of H20's HBM peak: there is no headroom for it to be larger. It
    cannot account for a 17% shortfall on a 1.06 s step, let alone on a 72 s one.
    """
    result = _scored()
    assert result.term_shares["optimizer"] < 0.02
    assert result.mre_percent > 10.0, (
        "the residual closed without the optimizer term growing; re-derive this test"
    )
