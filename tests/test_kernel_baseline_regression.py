"""The refactor must not move any measured accuracy number.

These are the ten quantities the KernelOp refactor is gated on. They were captured at
commit 72f00f5 before any edit, on H20 with Qwen3-8B at tp=1 and --fraction 1.0. The
refactor rebinds where SOL formulas are looked up, not what they compute, so every number
here must reproduce exactly. A change means the binding changed.

## Re-pinned 2026-10-09: decode attention is now timed by CUDA graph replay

`generation_attention` moved from CUDA-event timing to graph replay, because vLLM replays a
FULL captured graph for decode batches and therefore never pays the per-call python dispatch
that event timing was charging. The old table was flat at ~70 us from step 0 to 16384. A
256x range of KV work priced identically is the signature of a measurement dominated
by dispatch. It now reads 12.6 us at step 0 rising to 91.8 us at 32768, and scales with batch
too (22.6 us to 646 us from batch 1 to 64 at step 4096).

Two numbers moved in opposite directions and both are expected:

- **Composed decode MRE 4.84% -> 3.02%.** This is the end-to-end quantity, and 36 of 36
  layers are attention in this model, so the correction compounds per layer.
- **`generation_attention` holdout MRE 6.63% -> 11.55%.** Worse, and not a regression: the
  holdout fits a utility surface, and a surface over a constant is trivially accurate while
  one over real curvature is not. The old 6.63% was the easy fit of a table that had lost its
  physics. `context_attention` also moved (5.74% -> 6.46%) despite unchanged timing, because
  the two phases share a floor fit.

See `profiler/kernel/utils/timing.py` for the measurements and `cost/kernel/ops/base.py` for
why the policy is per-op rather than per-family.
"""

from __future__ import annotations

from pathlib import Path

import pytest

_REPO = Path(__file__).resolve().parents[1]
_TABLES = _REPO / "outputs" / "profile" / "qwen3_8b" / "kernel_tp1" / "kernel"
_BASELINE = _REPO / "outputs" / "profile" / "qwen3_8b" / "vllm_tp1" / "profiles" / "vllm.jsonl"
_CHECKPOINT = "/apdcephfs_zwfy/share_303760348/lhy/models/Qwen3-8B"

# These numbers are pinned to the measured parquet tables under `outputs/`, which is
# gitignored: profiling output is regenerated by running the sweep, not committed. So this file
# is a local instrument rather than a CI gate, and it skips cleanly on a fresh clone.
#
# The consequence to know about: re-running `srl-profile kernels run` overwrites those
# tables, and `latency_s` is a wall-clock measurement: two runs of identical code moved the
# GEMM holdout MRE from 3.896% to 3.828%, and six repeats of one kernel span 0.351% of their
# median. So a re-sweep will fail these assertions for reasons that have nothing to do with the
# code. Back the tables up first if you need to re-measure, or accept that these numbers must be
# re-pinned from the new sweep.
pytestmark = pytest.mark.skipif(
    not _TABLES.is_dir() or not _BASELINE.is_file(),
    reason="Measured perf tables and the vLLM baseline are machine-local.",
)

# (op_name, backend) -> (mre_percent, point_count)
_HOLDOUT = {
    ("gemm", "vllm"): (3.91, 64),
    ("context_attention", "vllm"): (6.46, 59),
    # 6.63 when this table was event-timed and flat. See the module docstring for why a
    # higher surface-fit error on physically correct data is the expected direction.
    ("generation_attention", "vllm"): (11.55, 72),
    ("context_attention", "flashinfer"): (10.08, 59),
    ("generation_attention", "flashinfer"): (6.42, 72),
}

# phase -> (mre_percent, bucket_count)
_VALIDATE_PCHIP = {
    # 4.84 before decode attention was timed by graph replay.
    "decode": (3.02, 216),
    "prefill": (3.84, 29),
    # 0.48 before the context-phase shape was read from `sum_l2` rather than
    # `n_tokens / request_count`. These five buckets are all near-uniform prompt
    # batches, where the two agree to within a token, and the new form is what makes
    # a resume sharing a step with a large decode batch price correctly.
    "mixed": (0.56, 5),
}

_FLOORS = {
    # `generation_attention` fits 6 us now rather than 22 us: the fitted floor was absorbing
    # python dispatch that the engine does not pay inside its captured decode graph.
    "vllm": {"context_attention": 32e-6, "generation_attention": 6e-6},
    "flashinfer": {"context_attention": 4e-6, "generation_attention": 6e-6},
}


def test_holdout_accuracy_has_not_moved():
    from srl.cost.kernel.holdout import holdout_report

    results = {(r.op_name, r.backend): r for r in holdout_report(_TABLES, gpu="h20", fraction=1.0)}
    for key, (mre, count) in _HOLDOUT.items():
        assert key in results, f"{key} disappeared from the holdout report"
        assert results[key].point_count == count, f"{key} point count moved"
        assert results[key].mre_percent == pytest.approx(mre, abs=0.01), f"{key} MRE moved"


def test_composed_model_accuracy_has_not_moved():
    from srl.cost.kernel.database import KernelDatabase
    from srl.cost.kernel.model_ops import ModelOps
    from srl.cost.kernel.validate import load_baseline, score_model
    from srl.cost.rollout.composed import ComposedRollout

    database = KernelDatabase.from_root(_TABLES, gpu="h20", utility_surface="pchip")
    ops = ModelOps.from_checkpoint(_CHECKPOINT, tensor_parallel=1)
    model = ComposedRollout(database, ops, tensor_parallel=1)
    buckets = load_baseline(_BASELINE, min_samples=1)
    results = {r.phase: r for r in score_model(model, buckets)}
    assert set(results) == set(_VALIDATE_PCHIP)
    for phase, (mre, count) in _VALIDATE_PCHIP.items():
        assert results[phase].bucket_count == count, f"{phase} bucket count moved"
        assert results[phase].mre_percent == pytest.approx(mre, abs=0.01), f"{phase} MRE moved"


@pytest.mark.parametrize("backend", sorted(_FLOORS))
def test_fitted_floors_have_not_moved(backend):
    """Floors are keyed by op name after this refactor. The values must not change."""
    from srl.cost.kernel.floor import load_floors

    backend_dir = _TABLES / "h20" / "attention" / backend
    versions = sorted(item for item in backend_dir.iterdir() if item.is_dir())
    assert len(versions) == 1, f"expected one version under {backend_dir}, got {versions}"
    floors = load_floors(versions[0], backend=backend, warn_missing=False)
    assert floors is not None, f"no floors.json under {versions[0]}"
    for op_name, value in _FLOORS[backend].items():
        assert floors[op_name] == pytest.approx(value, rel=1e-9), f"{backend}/{op_name} moved"
